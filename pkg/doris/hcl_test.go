func TestParseAndFormatHCL_Proto2TypeDorisAndIcebergSyntax(t *testing.T) {
	dorisHCL := `# Code generated by proto2type. DO NOT EDIT.
// Line comment with braces { } and quotes "
/* Block comment with { unbalanced brace and # hash */

schema "tenant_${TENANT_SLUG}" {
  catalog = "internal"
  charset = "utf8mb4"
  comment = "Tenant schema"
}

table "patient_note_chunks" {
  schema = "schema.tenant_${TENANT_SLUG}"
  comment = "Clinical note chunks with escaped backslash \\"
  column "tenant_id" {
    type = varchar(64)
    null = false
    comment = "Tenant identifier"
  }
  column "patient_id" {
    type = "VARCHAR(64)"
    null = false
  }
  column "chunk_id" {
    type = varchar(64)
    null = false
  }
  column "encounter_id" {
    type = varchar(64)
    null = true
  }
  column "event_month" {
    type = varchar(7)
    null = false
    default = "1970-01"
  }
  column "amount" {
    type = decimalv3(18, 4)
    null = false
    default = "0.0000"
  }
  column "tags" {
    type = array<varchar(64)>
    null = false
    default = "[]"
  }
  column "chunk_text" {
    type = text
    null = true
  }
  column "section_title" {
    type = varchar(256)
    null = true
  }
  column "updated_at" {
    type = datetimev2(6)
    null = false
    default = "1970-01-01 00:00:00"
  }
  unique_key {
    columns = [column.tenant_id, column.patient_id, column.chunk_id]
    merge_on_write = true
    sequence_col = column.updated_at
  }
  distributed_by_hash {
    columns = [column.patient_id]
    buckets = "${TENANT_BUCKETS}"
  }
  partition_by_list {
    columns = [column.event_month]
  }
  order_by {
    columns = [column.tenant_id, column.patient_id, column.updated_at]
  }
  index "idx_patient_note_chunks_encounter_id" {
    columns = [column.encounter_id]
    using = "INVERTED"
  }
  index "idx_chunk_text_bm25" {
    columns = [column.chunk_text]
    using = "INVERTED"
    properties = {
      parser = "english"
      support_phrase = "true"
      lower_case = "true"
    }
    comment = "BM25 index"
  }
  index "idx_ngram_patient_note_chunks_section_title" {
    columns = [column.section_title]
    type = "NGRAM_BF"
    properties = {
      gram_size = "3"
      bf_size = "1024"
    }
  }
  properties = {
    storage_vault_name = "custom_vault"
    compression = "zstd"
    enable_unique_key_merge_on_write = "true"
    "function_column.sequence_col" = "updated_at"
    colocate_with = "patient_group"
    "replication_num" = "1"
    bloom_filter_columns = "patient_id, encounter_id"
  }
}`

	schema, err := doris.ParseSchema(dorisHCL)
	if err != nil {
		t.Fatalf("ParseSchema(dorisHCL) failed: %v", err)
	}
	if len(schema.Databases) != 1 || schema.Databases[0].CanonicalName() != "internal.tenant_${TENANT_SLUG}" {
		t.Fatalf("expected database internal.tenant_${TENANT_SLUG}, got %+v", schema.Databases)
	}
	if len(schema.Tables) != 1 {
		t.Fatalf("expected 1 table, got %d", len(schema.Tables))
	}
	tbl := schema.Tables[0]
	if tbl.CanonicalName() != "internal.tenant_${TENANT_SLUG}.patient_note_chunks" {
		t.Errorf("unexpected table canonical name: %q", tbl.CanonicalName())
	}
	if tbl.Comment != `Clinical note chunks with escaped backslash \` {
		t.Errorf("unexpected table comment: %q", tbl.Comment)
	}
	if tbl.Key == nil || tbl.Key.Kind != doris.KeyUnique || len(tbl.Key.Columns) != 3 {
		t.Errorf("unexpected key clause: %+v", tbl.Key)
	}
	if tbl.SequenceCol() != "updated_at" || tbl.ColocateGroup() != "patient_group" {
		t.Errorf("unexpected sequence_col=%q colocate_with=%q", tbl.SequenceCol(), tbl.ColocateGroup())
	}
	if tbl.Distribution == nil || tbl.Distribution.Kind != "HASH" || tbl.Distribution.Buckets != "${TENANT_BUCKETS}" {
		t.Errorf("unexpected distribution: %+v", tbl.Distribution)
	}
	if tbl.Partition == nil || tbl.Partition.Kind != "LIST" || len(tbl.Partition.Columns) != 1 || tbl.Partition.Columns[0] != "event_month" {
		t.Errorf("unexpected partition: %+v", tbl.Partition)
	}
	if len(tbl.OrderBy) != 3 {
		t.Errorf("expected 3 order_by columns, got %v", tbl.OrderBy)
	}
	if len(tbl.Indexes) != 3 {
		t.Fatalf("expected 3 indexes, got %d", len(tbl.Indexes))
	}
	if tbl.Indexes[2].Using != "NGRAM_BF" {
		t.Errorf("expected 3rd index Using=NGRAM_BF, got %q", tbl.Indexes[2].Using)
	}

	// Verify FormatHCL -> ParseHCL round-trip idempotence
	formattedHCL1 := doris.FormatHCL(schema)
	reParsed, err := doris.ParseHCL(formattedHCL1)
	if err != nil {
		t.Fatalf("ParseHCL(FormatHCL) failed: %v\nHCL:\n%s", err, formattedHCL1)
	}
	formattedHCL2 := doris.FormatHCL(reParsed)
	if formattedHCL1 != formattedHCL2 {
		t.Fatalf("FormatHCL not idempotent:\n--- 1 ---\n%s\n--- 2 ---\n%s", formattedHCL1, formattedHCL2)
	}

	// Diff between original and round-tripped HCL must be empty
	stmts, err := doris.Diff(schema, reParsed)
	if err != nil {
		t.Fatalf("Diff(schema, reParsed) failed: %v", err)
	}
	if len(stmts) != 0 {
		t.Fatalf("expected 0 diff statements, got %d:\n%s", len(stmts), doris.FormatStatements(stmts))
	}
}

func TestParseHCL_Variants_DuplicateKey_ANN_Aggregate_Iceberg_AndInlineSyntax(t *testing.T) {
	hclText := `
table "clinical_concept_search" {
  schema = schema.terminology_rag
  column "concept_id" { type = varchar(64) null = false }
  column "code_system" { type = varchar(32), null = false }
  column "embedding" { type = array<float> null = false }
  duplicate_key { columns = ["concept_id", "code_system"] }
  distribution { type = "HASH", columns = [column.concept_id], buckets = 8 }
  partition_by_range { columns = [column.code_system] }
  index "idx_embedding_hnsw" {
    columns = [column.embedding]
    type = "ANN"
    properties = {
      index_type = "hnsw"
      metric_type = "l2_distance"
      dim = "768"
    }
  }
  properties = {
    compression = "zstd"
  }
}

table "metrics_rollup" {
  schema = schema.telemetry
  column "metric_date" { type = datev2 null = false }
  column "total_events" { type = bigint null = false agg_type = "SUM" default = "0" }
  aggregate_key { columns = [column.metric_date] }
  distribution { type = "RANDOM", buckets = "auto" }
  partition { kind = "RANGE", columns = [column.metric_date] }
}

table "patient_encounters" {
  catalog = "azra_lake"
  schema = schema.tenant_acme
  column "patient_id" { type = varchar(64) null = false }
  column "event_date" { type = date null = false }
  primary_key { columns = [column.patient_id] }
  partition_by { spec = "months(event_date)" }
  properties = {
    engine = "iceberg"
    "write.format.default" = "parquet"
    "write.parquet.compression-codec" = "zstd"
  }
}
`
	s, err := doris.ParseSchemaAuto(hclText, "test_doris.hcl")
	if err != nil {
		t.Fatalf("ParseSchemaAuto failed: %v", err)
	}
	if len(s.Tables) != 3 {
		t.Fatalf("expected 3 tables, got %d", len(s.Tables))
	}

	if violations := doris.LintSchema(s); len(violations) != 0 {
		t.Fatalf("expected 0 lint violations, got %v", violations)
	}

	rag := s.Tables[0]
	if rag.CanonicalName() != "internal.terminology_rag.clinical_concept_search" {
		t.Errorf("unexpected rag canonical name: %q", rag.CanonicalName())
	}
	if rag.Key == nil || rag.Key.Kind != doris.KeyDuplicate {
		t.Errorf("expected DUPLICATE KEY on rag, got %+v", rag.Key)
	}

	agg := s.Tables[1]
	if agg.Key == nil || agg.Key.Kind != doris.KeyAggregate {
		t.Errorf("expected AGGREGATE KEY on metrics_rollup, got %+v", agg.Key)
	}
	if agg.Columns[1].AggType != "SUM" {
		t.Errorf("expected AggType=SUM, got %q", agg.Columns[1].AggType)
	}
	if agg.Distribution == nil || agg.Distribution.Kind != "RANDOM" || agg.Distribution.Buckets != "AUTO" {
		t.Errorf("unexpected RANDOM distribution: %+v", agg.Distribution)
	}

	ice := s.Tables[2]
	if !ice.IsIcebergTable() || ice.CanonicalName() != "azra_lake.tenant_acme.patient_encounters" {
		t.Errorf("expected Iceberg table azra_lake.tenant_acme.patient_encounters, got %q (isIceberg=%v)", ice.CanonicalName(), ice.IsIcebergTable())
	}
	if ice.Partition == nil || ice.Partition.Kind != "EXPR" || ice.Partition.RawExpr != "months(event_date)" {
		t.Errorf("unexpected Iceberg partition: %+v", ice.Partition)
	}

	// Round-trip FormatHCL -> ParseHCL
	hclOut := doris.FormatHCL(s)
	s2, err := doris.ParseHCL(hclOut)
	if err != nil {
		t.Fatalf("re-parse FormatHCL failed: %v\n%s", err, hclOut)
	}
	if doris.FormatHCL(s2) != hclOut {
		t.Fatalf("FormatHCL round-trip mismatch:\nwant:\n%s\ngot:\n%s", hclOut, doris.FormatHCL(s2))
	}
}

func TestFormatHCL_RealPlatformSchemasRoundTrip(t *testing.T) {
	schemasDir := "/Users/ab/code/azra/platform/schemas/iceberg"
	if _, err := os.Stat(schemasDir); os.IsNotExist(err) {
		t.Skipf("platform schemas directory %s not present", schemasDir)
	}

	for _, file := range []string{"doris_tenant_profile_ddl.sql", "iceberg_tenant_profile_ddl.sql"} {
		t.Run(file, func(t *testing.T) {
			raw, err := os.ReadFile(filepath.Join(schemasDir, file))
			if err != nil {
				t.Fatalf("read %s: %v", file, err)
			}
			sqlSchema, err := doris.ParseSchema(string(raw))
			if err != nil {
				t.Fatalf("ParseSchema(%s): %v", file, err)
			}
			hcl1 := doris.FormatHCL(sqlSchema)
			hclSchema, err := doris.ParseHCL(hcl1)
			if err != nil {
				t.Fatalf("ParseHCL(%s): %v", file, err)
			}
			hcl2 := doris.FormatHCL(hclSchema)
			if hcl1 != hcl2 {
				t.Fatalf("FormatHCL not idempotent on %s", file)
			}
			stmts, err := doris.Diff(sqlSchema, hclSchema)
			if err != nil {
				t.Fatalf("Diff(sqlSchema, hclSchema) on %s failed: %v", file, err)
			}
			if len(stmts) != 0 {
				t.Fatalf("expected 0 diff statements between SQL and HCL schemas for %s, got %d:\n%s", file, len(stmts), doris.FormatStatements(stmts))
			}
		})
	}
}

func TestParseHCL_InvalidInputs(t *testing.T) {
	badInputs := []string{
		`table "unclosed" {`,
		`table "bad-name!" { column "a" { type = int } }`,
		`table "t" { column "c" { type = "unterminated } }`,
		`table "t" { /* unclosed block comment }`,
		`table "t" { unknown_block {} }`,
		`table "t" { column "c" { null = false } }`,
		`table "t" {}`,
		`unexpected_block "x" {}`,
	}
	for _, src := range badInputs {
		if _, err := doris.ParseHCL(src); err == nil {
			t.Errorf("expected error from ParseHCL(%q), got nil", src)
		}
	}
}

