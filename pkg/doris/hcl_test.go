func TestFormatColumnDef_ArrayEmptyDefaultUnquoted(t *testing.T) {
	sqlText := `
CREATE TABLE IF NOT EXISTS internal.tenant_test.items (
    item_id VARCHAR(64) NOT NULL,
    tags ARRAY<VARCHAR(64)> NOT NULL DEFAULT "[]"
)
UNIQUE KEY(item_id)
DISTRIBUTED BY HASH(item_id) BUCKETS 4;`

	s, err := doris.ParseSchema(sqlText)
	if err != nil {
		t.Fatalf("ParseSchema: %v", err)
	}
	formatted := doris.FormatSchema(s)
	if !strings.Contains(formatted, "tags ARRAY<VARCHAR(64)> NOT NULL DEFAULT []") {
		t.Fatalf("expected unquoted DEFAULT [] for ARRAY column, got:\n%s", formatted)
	}
	reParsed, err := doris.ParseSchema(formatted)
	if err != nil {
		t.Fatalf("re-parse unquoted DEFAULT [] failed: %v", err)
	}
	if doris.FormatSchema(reParsed) != formatted {
		t.Fatalf("round-trip mismatch on DEFAULT []")
	}
}
